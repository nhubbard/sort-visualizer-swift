def sort(arr):
    for i in range(len(arr) - 1):
        min_index = i
        for j in range(i + 1, len(arr)):
            if arr[j] < arr[min_index]:
                min_index = j
        tmp = arr[min_index]
        pos = min_index
        while pos > i:
            arr[pos] = arr[pos - 1]
            pos -= 1
        arr[pos] = tmp


if __name__ == "__main__":
    array = [0, 39, 21, 62, 91, 77, 14, 23, 90, 69, 51, 81, 68, 83, 32, 56]
    sort(array)
    print(array)
